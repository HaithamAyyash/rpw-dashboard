// Bundles db/queries/*.sql into TypeScript, so the web image doesn't need the db/ folder at
// runtime. Run after changing a query: npm run queries. A test fails if this is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const QUERY_DIR = path.resolve(__dirname, "../../db/queries");
const TARGET = path.resolve(__dirname, "../lib/db/queries.generated.ts");

export function generatedQueries(): string {
  const entries = readdirSync(QUERY_DIR)
    .filter((name) => name.endsWith(".sql"))
    .sort()
    .map((name) => {
      const sql = readFileSync(path.join(QUERY_DIR, name), "utf8");
      return `  ${name.replace(".sql", "")}: ${JSON.stringify(sql)},`;
    });
  return `// Generated by scripts/gen-queries.ts from db/queries; do not edit.\nexport const queries = {\n${entries.join("\n")}\n} as const;\n`;
}

if (process.argv[1]?.endsWith("gen-queries.ts")) {
  writeFileSync(TARGET, generatedQueries());
  console.log(`wrote ${TARGET}`);
}
